"""Характеры как поведенческие карточки, а не прилагательные.

Каждая карточка задаёт измеримое поведение: инициативу, длину реплик,
частоту встречных вопросов, открытость, реакцию на неловкость и манеру речи.
"""

from dataclasses import dataclass


@dataclass(frozen=True)
class PersonaCard:
    initiative: str
    reply_length: str
    questions: str
    openness: str
    on_awkwardness: str
    speech: str
    never: str

    def render(self) -> str:
        return (
            f"- Инициатива: {self.initiative}\n"
            f"- Длина реплик: {self.reply_length}\n"
            f"- Встречные вопросы: {self.questions}\n"
            f"- Открытость: {self.openness}\n"
            f"- Неловкие паузы и странные реплики: {self.on_awkwardness}\n"
            f"- Манера речи: {self.speech}\n"
            f"- Никогда: {self.never}"
        )


